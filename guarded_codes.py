def load_guarded_codes_from_file(filepath: str = "Security_Cargo_GNG.txt") -> list:
    """Парсит файл Security_Cargo_GNG.txt и извлекает коды с флагом охраны '1'."""
    if not os.path.exists(filepath):
        return []
    
    codes = []
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            for line in f:
                if "|" in line:
                    parts = [p.strip() for p in line.split("|")]
                    if len(parts) >= 3:
                        raw_code = parts[1].replace("*", "").strip()
                        mode = parts[2].replace("*", "").strip()
                        clean_c = re.sub(r'\D', '', raw_code)
                        if clean_c and mode == "1":
                            codes.append(clean_c)
    except Exception as e:
        print(f"Error reading {filepath}: {e}")
        return []
    return codes

def build_guarded_lookup_set() -> set:
    """Формирует индекс быстрого поиска с учетом 2-, 4- и 8-значных префиксов."""
    codes = load_guarded_codes_from_file()
    if not codes:
        codes = EMBEDDED_GUARDED_CODES

    lookup = set()
    for code in codes:
        clean = code.lstrip('0')
        lookup.add(code)
        lookup.add(clean)
        lookup.add(code.ljust(8, '0'))
        
        if len(clean) >= 4:
            lookup.add(clean[:4])
            lookup.add(clean[:4].ljust(8, '0'))
        if len(code) >= 4:
            lookup.add(code[:4])
            lookup.add(code[:4].ljust(8, '0'))
        if len(clean) >= 2:
            lookup.add(clean[:2])
            
    return lookup

GUARDED_LOOKUP_SET = build_guarded_lookup_set()

def is_cargo_guarded(gng_code: str) -> bool:
    """Проверяет, подлежит ли груз с указанным кодом ГНГ обязательной охране."""
    if not gng_code:
        return False

    clean_input = re.sub(r'\D', '', str(gng_code))
    if not clean_input:
        return False

    padded_right = clean_input.ljust(8, '0')
    padded_left = clean_input.zfill(8)
    prefix_4 = clean_input[:4]
    prefix_2 = clean_input[:2]

    return (
        clean_input in GUARDED_LOOKUP_SET
        or padded_right in GUARDED_LOOKUP_SET
        or padded_left in GUARDED_LOOKUP_SET
        or prefix_4 in GUARDED_LOOKUP_SET
        or prefix_2 in GUARDED_LOOKUP_SET
    )
