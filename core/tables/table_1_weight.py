def calculate_billable_weight(weight_tons: int) -> int:
    """
    Рассчитывает расчетную категорию веса по Таблице 1.
    
    Диапазоны (в тоннах):
      0..12  -> 10
      13..16 -> 15
      17..23 -> 20
      24..26 -> 25
      27..31 -> 30
      32..36 -> 35
      37..40 -> 40
      41..46 -> 45
      47..51 -> 50
      52..55 -> 55
      56..60 -> 60
      > 60   -> фактический вес (61 -> 61)
    """
    w = int(weight_tons)
    
    if w <= 12:
        return 10
    elif w <= 16:
        return 15
    elif w <= 23:
        return 20
    elif w <= 26:
        return 25
    elif w <= 31:
        return 30
    elif w <= 36:
        return 35
    elif w <= 40:
        return 40
    elif w <= 46:
        return 45
    elif w <= 51:
        return 50
    elif w <= 55:
        return 55
    elif w <= 60:
        return 60
    else:
        return w
